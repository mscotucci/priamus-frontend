// Generates src/styles/tokens.css and src/styles/theme.css from design-system/tokens.json.
// tokens.css declares the design tokens as CSS custom properties, per theme.
// theme.css maps them into the Tailwind theme, so a utility can only name a value of the system.
import { readFile, writeFile } from 'node:fs/promises';

const tokens = JSON.parse(await readFile('design-system/tokens.json', 'utf8'));
const themes = tokens.color.themes.map((t) => t.id);
const [first, ...others] = themes;
const perTheme = (token, theme) =>
  typeof token.value === 'string' ? token.value : (token.value[theme] ?? token.value[first]);
const themed = [...tokens.color.tokens, ...(tokens.shadow?.tokens ?? [])];
const block = (selector, lines) => `${selector} {\n${lines.map((l) => `  ${l}`).join('\n')}\n}\n`;

const header =
  '/* Generated by scripts/tokens.mjs from design-system/tokens.json. Do not edit. */\n\n';
const tokensCss =
  header +
  block(
    `:root,\n[data-theme='${first}']`,
    themed.map((t) => `--${t.name}: ${perTheme(t, first)};`),
  ) +
  others
    .map(
      (theme) =>
        '\n' +
        block(
          `[data-theme='${theme}']`,
          themed
            .filter((t) => typeof t.value !== 'string' && t.value[theme] !== undefined)
            .map((t) => `--${t.name}: ${t.value[theme]};`),
        ),
    )
    .join('') +
  '\n' +
  block(':root', [
    ...tokens.spacing.tokens.map((t) => `--${t.name}: ${t.value};`),
    ...tokens.radius.tokens.map((t) => `--${t.name}: ${t.value};`),
    ...Object.entries(tokens.type.families).map(([key, stack]) => `--font-${key}: ${stack};`),
  ]);

// Colours and shadows follow the theme, so the Tailwind theme points at the custom properties;
// radii and fonts do not change with the theme and are written as values.
const themeCss =
  header +
  block('@theme inline', [
    '--color-*: initial;',
    ...tokens.color.tokens.map((t) => `--color-${t.name}: var(--${t.name});`),
    '--shadow-*: initial;',
    ...(tokens.shadow?.tokens ?? []).map(
      (t) => `--shadow-${t.name.replace(/^shadow-/, '')}: var(--${t.name});`,
    ),
    '--radius-*: initial;',
    ...tokens.radius.tokens.map((t) => `--${t.name}: ${t.value};`),
    '--font-*: initial;',
    ...Object.entries(tokens.type.families).map(([key, stack]) => `--font-${key}: ${stack};`),
  ]);

await writeFile('src/styles/tokens.css', tokensCss);
await writeFile('src/styles/theme.css', themeCss);
console.log('Generated src/styles/tokens.css and src/styles/theme.css');
